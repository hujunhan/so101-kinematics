"""S1 benchmark (simulation only): my 2023 arm_control vs Pinocchio on the SO-101.

1. FK: legacy numeric FK vs Pinocchio on random joint configurations within the URDF limits.
2. Position-only IK, the problem the 2023 code solves: random reachable targets (FK of random
   in-limit configurations), all solvers start from the zero pose.
   Metrics: success (error < 2 mm), joint-limit violations among successes, time per solve.

Writes results/s1_benchmark.md and results/s1_benchmark.json.
"""

import json
import time
from pathlib import Path

import numpy as np

from so101_kinematics.models import HI, LO, LegacyArm, N, PinArm

SEED, N_FK, N_IK, TOL = 0, 1000, 200, 0.002
OUT = Path(__file__).resolve().parent.parent / "results"


def main() -> None:
    rng = np.random.default_rng(SEED)
    legacy, ref = LegacyArm(), PinArm()

    # 1. FK agreement
    pos_err, rot_err = [], []
    for _ in range(N_FK):
        q = rng.uniform(LO, HI)
        a, b = legacy.fk(q), ref.fk(q)
        pos_err.append(np.linalg.norm(a[:3, 3] - b[:3, 3]))
        rot_err.append(np.linalg.norm(a[:3, :3] - b[:3, :3]))
    fk = {"n": N_FK, "pos_err_max_m": float(max(pos_err)), "rot_err_max": float(max(rot_err))}

    # 2. Position-only IK
    targets = [ref.fk(rng.uniform(LO, HI))[:3, 3] for _ in range(N_IK)]
    q0 = np.zeros(N)
    solvers = {
        "arm_control ik_jacobian (pseudo-inverse)": lambda t: legacy.ik_jacobian(t, q0, "inverse"),
        "arm_control ik_jacobian (transpose)": lambda t: legacy.ik_jacobian(t, q0, "transpose"),
        "arm_control ik_scipy (SLSQP + limits)": lambda t: legacy.ik_scipy(t, q0),
        "Pinocchio DLS (reference, no limits)": lambda t: ref.ik_dls_position(t, q0),
    }
    ik = {}
    for name, solve in solvers.items():
        times, errs, viol = [], [], []
        for t in targets:
            t0 = time.perf_counter()
            q = solve(t)
            times.append(time.perf_counter() - t0)
            errs.append(np.linalg.norm(ref.fk(q)[:3, 3] - t))  # judged by the reference FK
            viol.append(bool(np.any((q < LO - 1e-6) | (q > HI + 1e-6))))
        errs, viol = np.array(errs), np.array(viol)
        ok = errs < TOL
        ik[name] = {
            "success": int(ok.sum()),
            "success_within_limits": int((ok & ~viol).sum()),
            "violations_among_successes": int((ok & viol).sum()),
            "median_err_mm": float(np.median(errs) * 1e3),
            "median_ms": float(np.median(times) * 1e3),
            "p95_ms": float(np.percentile(times, 95) * 1e3),
        }
        print(f"{name}: {ik[name]}")

    OUT.mkdir(exist_ok=True)
    (OUT / "s1_benchmark.json").write_text(json.dumps({"seed": SEED, "fk": fk, "ik": ik}, indent=2))
    lines = [
        "# S1 benchmark: arm_control (2023) vs Pinocchio on the SO-101",
        "",
        f"Simulation only. Seed {SEED}. Tool frame `gripper_frame_link`. Generated by `benchmarks/s1_benchmark.py`.",
        "",
        "## Forward kinematics",
        "",
        f"{N_FK} random configurations within the URDF limits: max position difference "
        f"**{fk['pos_err_max_m']:.1e} m**, max rotation-matrix difference **{fk['rot_err_max']:.1e}**.",
        "",
        "## Position-only IK",
        "",
        f"{N_IK} reachable targets (FK of random in-limit configurations); every solver starts from the zero pose; "
        f"success = error < {TOL * 1e3:.0f} mm, judged with Pinocchio FK.",
        "",
        "| Solver | Success | Success within limits | Limit violations | Median error (mm) | Median time (ms) | p95 time (ms) |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for name, r in ik.items():
        lines.append(
            f"| {name} | {r['success']}/{N_IK} | {r['success_within_limits']}/{N_IK} | "
            f"{r['violations_among_successes']} | {r['median_err_mm']:.2f} | {r['median_ms']:.1f} | {r['p95_ms']:.1f} |"
        )
    (OUT / "s1_benchmark.md").write_text("\n".join(lines) + "\n")
    print(f"\nwrote {OUT / 's1_benchmark.md'}")


if __name__ == "__main__":
    main()
